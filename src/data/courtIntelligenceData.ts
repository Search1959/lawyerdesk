export const postgresqlSchemaDDL = `-- =====================================================================
-- LAWYERDESK AI - COURT INTELLIGENCE & LITIGATION COMMAND CENTER
-- Enterprise PostgreSQL Production Database Schema DDL
-- Supported Engine: PostgreSQL 15+ / Cloud SQL / Supabase
-- Multi-Tenant Schema Isolation Enabled
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. COURTS DIRECTORY TABLE
CREATE TABLE IF NOT EXISTS public.courts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    court_code VARCHAR(64) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL, -- Supreme Court, High Court, District Court, NCLT, DRT, etc.
    state VARCHAR(100) NOT NULL,
    city VARCHAR(100) NOT NULL,
    address TEXT NOT NULL,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    jurisdiction TEXT NOT NULL,
    contact_phones JSONB DEFAULT '[]'::jsonb,
    email VARCHAR(150),
    website VARCHAR(255),
    timings VARCHAR(100),
    working_days VARCHAR(100),
    cause_list_url TEXT,
    filing_procedure_summary TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. JUDGES DIRECTORY TABLE
CREATE TABLE IF NOT EXISTS public.judges (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    court_id UUID REFERENCES public.courts(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    designation VARCHAR(150) NOT NULL,
    bench_type VARCHAR(100) NOT NULL, -- Single Bench, Division Bench, Full Bench
    court_room_no VARCHAR(50),
    current_assignment TEXT,
    appointed_date DATE,
    retirement_date DATE,
    transfer_history JSONB DEFAULT '[]'::jsonb,
    notable_judgments JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. MATTERS & LITIGATION MASTER TABLE
CREATE TABLE IF NOT EXISTS public.matters (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    firm_id UUID NOT NULL,
    case_number VARCHAR(100) NOT NULL,
    cnr_number VARCHAR(32) UNIQUE,
    title VARCHAR(300) NOT NULL,
    category VARCHAR(100) NOT NULL,
    court_id UUID REFERENCES public.courts(id),
    judge_id UUID REFERENCES public.judges(id),
    court_room_no VARCHAR(50),
    stage VARCHAR(100) NOT NULL,
    status VARCHAR(50) DEFAULT 'Active Litigation',
    client_id UUID NOT NULL,
    opposing_party VARCHAR(255),
    opposing_advocate VARCHAR(255),
    lead_lawyer_id UUID NOT NULL,
    acts_and_sections JSONB DEFAULT '[]'::jsonb,
    risk_score INT CHECK (risk_score BETWEEN 0 AND 100),
    ai_summary TEXT,
    next_hearing_date DATE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. CAUSE LISTS TABLE
CREATE TABLE IF NOT EXISTS public.cause_lists (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    court_id UUID REFERENCES public.courts(id) ON DELETE CASCADE,
    judge_id UUID REFERENCES public.judges(id),
    date DATE NOT NULL,
    item_no INT NOT NULL,
    case_number VARCHAR(100) NOT NULL,
    cnr_number VARCHAR(32),
    parties_title TEXT NOT NULL,
    petitioner_advocate VARCHAR(255),
    respondent_advocate VARCHAR(255),
    stage VARCHAR(100),
    estimated_time VARCHAR(50),
    prep_status VARCHAR(50) DEFAULT 'Draft Pending',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 5. HEARINGS & DAILY ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.hearings (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    matter_id UUID REFERENCES public.matters(id) ON DELETE CASCADE,
    hearing_date DATE NOT NULL,
    hearing_time VARCHAR(20),
    judge_id UUID REFERENCES public.judges(id),
    court_room_no VARCHAR(50),
    stage VARCHAR(100) NOT NULL,
    synopsis TEXT,
    outcome TEXT,
    next_hearing_date DATE,
    assigned_lawyer_id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 6. COURT ORDERS & JUDGMENTS TABLE
CREATE TABLE IF NOT EXISTS public.court_orders (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    matter_id UUID REFERENCES public.matters(id) ON DELETE CASCADE,
    order_date DATE NOT NULL,
    order_type VARCHAR(100) NOT NULL, -- Interim Order, Injunction, Final Judgment
    judge_name VARCHAR(255),
    summary TEXT NOT NULL,
    key_directives JSONB DEFAULT '[]'::jsonb,
    pdf_document_id UUID,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 7. KNOWLEDGE GRAPH NODES & EDGES TABLE
CREATE TABLE IF NOT EXISTS public.knowledge_graph_nodes (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    matter_id UUID REFERENCES public.matters(id) ON DELETE CASCADE,
    node_key VARCHAR(100) NOT NULL,
    label VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL, -- Client, Matter, Court, Judge, Document, Order, Evidence, etc.
    details TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.knowledge_graph_edges (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    source_node_id UUID REFERENCES public.knowledge_graph_nodes(id) ON DELETE CASCADE,
    target_node_id UUID REFERENCES public.knowledge_graph_nodes(id) ON DELETE CASCADE,
    relationship_label VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 8. CASE HEALTH & AI RECOMMENDATIONS TABLE
CREATE TABLE IF NOT EXISTS public.case_health_scores (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    matter_id UUID UNIQUE REFERENCES public.matters(id) ON DELETE CASCADE,
    score_percentage INT NOT NULL DEFAULT 85,
    client_details_complete BOOLEAN DEFAULT TRUE,
    evidence_complete BOOLEAN DEFAULT TRUE,
    witness_ready BOOLEAN DEFAULT TRUE,
    cross_exam_ready BOOLEAN DEFAULT TRUE,
    documents_uploaded BOOLEAN DEFAULT TRUE,
    fees_paid BOOLEAN DEFAULT TRUE,
    timeline_updated BOOLEAN DEFAULT TRUE,
    limitation_safe BOOLEAN DEFAULT TRUE,
    ai_recommendations JSONB DEFAULT '[]'::jsonb,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- INDEXES FOR HIGH PERFORMANCE LITIGATION SEARCH
CREATE INDEX IF NOT EXISTS idx_matters_cnr ON public.matters(cnr_number);
CREATE INDEX IF NOT EXISTS idx_matters_firm ON public.matters(firm_id);
CREATE INDEX IF NOT EXISTS idx_cause_lists_date ON public.cause_lists(date);
CREATE INDEX IF NOT EXISTS idx_hearings_date ON public.hearings(hearing_date);
`;
